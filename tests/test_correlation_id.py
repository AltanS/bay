"""Tests for M78-S8: correlation ID end-to-end push tracing.

Verifies that:
1. Trigger files with two lines → CORR_ID set to line 1 (UUID)
2. Legacy single-line trigger files → CORR_ID set to "unknown"
3. No trigger file (manual invocation) → CORR_ID starts with "manual-"
4. All rebuild.sh log output includes [${CORR_ID:-no-corr}] prefix via _log()
5. notify_build auto-appends correlation ID footer when CORR_ID is set
   and not "unknown"

Known limitation: cross-region correlation. The corr_id generated by the
webhook receiver on region EU is written to EU's trigger file. When EU
fans out a push to NA via the forward mechanism, NA's webhook generates
its OWN corr_id for its trigger file. The corr_ids on EU and NA are
therefore different for the same push. Cross-region correlation currently
requires matching on the GitHub delivery ID (X-GitHub-Delivery header)
in the webhook logs, not the corr_id. This is documented as a known
limitation — fixing it would require forwarding the originator's corr_id
in the fanout request body.
"""


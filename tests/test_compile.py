@pytest.fixture
def fleet(tmp_path: Path) -> Path:
    dest = tmp_path / "fleet"
    shutil.copytree(FIXTURE, dest)
    return dest


def edit(root: Path, rel: Path, old: str, new: str) -> None:
    path = root / rel
    text = path.read_text()
    assert old in text, f"{old!r} not in {rel}"
    path.write_text(text.replace(old, new, 1))


def edit_lock(root: Path, change: Any) -> None:
    path = root / LOCK
    data = json.loads(path.read_text())
    change(data)
    path.write_text(json.dumps(data, indent=2))


def compiled(root: Path) -> compiler.CompileResult:
    return compiler.compile_fleet(load_inputs(root))


def problems(root: Path) -> list[str]:
    with pytest.raises((compiler.CompileError, FleetError)) as info:
        compiled(root)
    return list(info.value.lines)


def todo_features(root: Path) -> set[str]:
    return {u.feature for u in compiled(root).unsupported}


def cli(root: Path, *args: str) -> Any:
    return runner.invoke(app, ["compile", "--fleet", str(root), *args])


def said(result: Any) -> str:
    """Everything a person sees: output, plus a BayError and its hint (main() prints those)."""
    exc = result.exception
    extra = f"\n{exc}\n{getattr(exc, 'hint', '') or ''}" if exc and not isinstance(exc, SystemExit) else ""
    return result.output + extra



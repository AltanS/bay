def test_compiled_file_passes_todays_validation(data: dict[str, Any]) -> None:
    from bay_cli.commands import validate as v

    result = v.ValidationResult()
    plain = v._validate_services_schema(ROOT, {"group_vars/all/services.yml": data}, result)
    assert plain is not None
    v._validate_identifier_safety(plain, result)
    v._validate_reserved_names(plain, result)
    v._validate_memswap_limits(plain, result)
    v._check_domain_uniqueness(plain["services"], result)
    v._check_depends_on(plain["services"], plain["accessories"], result)
    assert result.failed == [], result.failed


def _secret_names(text: str, parsed: dict[str, Any]) -> set[str]:
    names = set(re.findall(r"secrets(?:\.|\[')([A-Z0-9_]+)", text))
    for block in (*parsed["services"].values(), *parsed["accessories"].values()):
        secret = block.get("env", {}).get("secret")
        if isinstance(secret, dict):
            names |= set(secret.values())
    return names


def test_compile_fixture_fleet_feeds_build_specs(fleet: Path, tmp_path: Path) -> None:
    """The reconciler's build_specs.yml (and env.j2) accept the compiled file."""
    text = compiled(fleet).text()
    parsed = yaml.safe_load(text)

    def active(block: dict[str, Any]) -> dict[str, Any]:
        return {k: v for k, v in block.items() if not v.get("regions") or "eu" in v["regions"]}

    shop = parsed["services"]["shop"]
    play_vars = {
        "stack_dir": str(tmp_path / "stack"),
        "stack_name": "minfleet",
        "secrets": {k: f"pw-{k.lower()}" for k in _secret_names(text, parsed)},
        "gateway_bind_ip": "100.64.0.3",
        "bay_alert_host": "eu-1",
        "services": parsed["services"],
        "accessories": parsed["accessories"],
        "webhook": parsed["webhook"],
        "active_services": active(parsed["services"]),
        "active_accessories": active(parsed["accessories"]),
        "env_service_name": "shop",
        "env_clear": shop["env"]["clear"],
        "env_secrets": shop["env"]["secret"],
        "env_database": shop["database"],
    }
    (tmp_path / "vars.json").write_text(json.dumps(play_vars))
    (tmp_path / "ansible.cfg").write_text("[defaults]\n")
    specs, env_file = tmp_path / "specs.json", tmp_path / "shop.env"
    (tmp_path / "play.yml").write_text(
        "- hosts: localhost\n"
        "  connection: local\n"
        "  gather_facts: false\n"
        "  tasks:\n"
        f"    - ansible.builtin.include_tasks: {ROOT / 'roles/container_lifecycle/tasks/build_specs.yml'}\n"
        "    - ansible.builtin.copy:\n"
        "        content: '{{ container_specs | to_nice_json }}'\n"
        f"        dest: {specs}\n"
        "        mode: '0600'\n"
        "    - ansible.builtin.template:\n"
        f"        src: {ROOT / 'roles/deploy_stack/templates/env.j2'}\n"
        f"        dest: {env_file}\n"
        "        mode: '0600'\n"
    )
    plugins = os.pathsep.join(
        [str(ROOT / "roles/container_lifecycle/filter_plugins"), str(ROOT / "filter_plugins")]
    )
    env = {
        **os.environ,
        "ANSIBLE_FILTER_PLUGINS": plugins,
        "ANSIBLE_CONFIG": str(tmp_path / "ansible.cfg"),
        "ANSIBLE_NOCOLOR": "1",
        "ANSIBLE_LOCALHOST_WARNING": "0",
        "ANSIBLE_INVENTORY_UNPARSED_WARNING": "0",
        "ANSIBLE_PYTHON_INTERPRETER": sys.executable,
    }
    proc = subprocess.run(
        [sys.executable, "-m", "ansible.cli.playbook", "-i", "localhost,",
         "-e", f"@{tmp_path / 'vars.json'}", str(tmp_path / "play.yml")],
        cwd=tmp_path, env=env, capture_output=True, text=True, timeout=300,
    )
    assert proc.returncode == 0, proc.stdout[-3000:] + proc.stderr[-3000:]

    by_name = {s["name"]: s for s in json.loads(specs.read_text())}
    expected = set(active(parsed["services"])) | set(active(parsed["accessories"]))
    assert expected <= set(by_name)
    assert "gatus" not in by_name, "gatus runs on the na box"
    assert by_name["shop"]["type"] == "service"
    assert by_name["shop"]["ports"] == ["100.64.0.3:3000:3000"]
    assert by_name["shop"]["mem_limit"] == "512m" and "memswap_limit" not in by_name["shop"]
    labels = by_name["shop"]["labels"]
    assert labels["traefik.http.routers.shop-health.rule"].startswith("(Host(`shop.example.com`)")
    assert "shop-basicauth" in labels["traefik.http.routers.shop.middlewares"]
    staging = by_name["shop-staging"]["labels"]
    assert "traefik.http.routers.shop-staging-vpn.rule" in staging, "tailnet compiles to vpn"
    assert by_name["shop-warmer"]["type"] == "accessory"
    assert by_name["postgres"]["ports"] == ["127.0.0.1:5432:5432"]

    lines = dict(
        line.split("=", 1) for line in env_file.read_text().splitlines()
        if line and not line.startswith("#")
    )
    assert lines["SHOP_DATABASE_URL"] == lines["DATABASE_URL"]
    assert lines["SESSION_SECRET"] == "pw-shop_session_secret"
    assert lines["WARMER_URL"] == "http://shop-warmer:9000"

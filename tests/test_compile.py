def test_messages_use_no_banned_words(fleet: Path) -> None:
    """Every message a person sees, except the fixed TODO(role) marker."""
    samples = []
    for rel, old, new, _f in [p.values for p in UNSUPPORTED]:
        root = fleet.parent / f"u{len(samples)}"
        shutil.copytree(FIXTURE, root)
        edit(root, rel, old, new)
        samples.extend(u.feature for u in compiled(root).unsupported)
    for case in (
        lambda r: edit(r, SHOP, "publish = true", "publish = false"),
        lambda r: edit_lock(r, lambda d: d.update(repo=None)),
        lambda r: edit(r, FLEET, 'group = "na"\n', ""),
        lambda r: edit(r, GATUS, 'box = "na-1"', 'box = "us-9"'),
        lambda r: edit(r, SHOP, 'LOG_LEVEL = "info"', 'LOG_LEVEL = "info"\nDB_HOST = "x"'),
        lambda r: edit_lock(r, lambda d: d["envs"].update(qa={})),
    ):
        root = fleet.parent / f"e{len(samples)}"
        shutil.copytree(FIXTURE, root)
        case(root)
        samples.extend(problems(root))
    hits = [m for m in samples if BANNED.search(m)]
    assert hits == []



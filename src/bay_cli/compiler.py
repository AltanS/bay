"""``bay compile``: fleet file + pinned bay.toml files -> ``group_vars/all/services.yml``.

A pure function of its inputs (see :mod:`bay_cli.fleet`): the same inputs give
byte-identical output. The output carries a hash header; a hand edit makes the
next compile refuse (the command checks that, see ``commands/compile_cmd.py``).

Mapping, one bay.toml environment at a time:

* Container names: ``<name>`` for the primary env, ``<name>-<env>`` otherwise;
  extra services ``<name>-<service>`` / ``<name>-<env>-<service>``. The
  services.yml key IS the container name. Lockfile ``adopted.containers``
  (keyed by service, the main container is ``web``) wins.
* A routed container (``public``/``tailnet``, or a service with ``domain``)
  becomes a ``services:`` entry. An unrouted one (``internal``, or a service
  with neither ``domain`` nor ``path``) becomes an ``accessories:`` entry:
  today that is the only way to run a container with no router.
* ``health`` maps to ``healthcheck_path`` (the probe and the password
  carve-out), never to the Docker ``healthcheck`` block.
* Secret names resolve to the secret ``<MAIN CONTAINER>_<NAME>``, so every
  container of one project environment reads the same value.
* Features the deploy code cannot express yet are reported as
  :class:`Unsupported` (``# TODO(role)``) and the command refuses unless
  ``--allow-unsupported``; with it, the closest expressible form is emitted.

Collisions (container, router, volume, domain, database, database user and
variable names) are errors that name both sides. Nothing is last-wins.

Fleet-wide: ``[webhook]`` becomes ``webhook:`` and ``[tailnet.routes.*]``
becomes ``tailnet_proxies:`` (see :mod:`bay_cli.routes`). The compile refuses
when a hand file in ``group_vars/all`` still defines ``tailnet_proxies`` and
the fleet file has routes: both would set the same variable.
"""

from __future__ import annotations

import copy
import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from bay_cli import routes
from bay_cli.bay_toml import sibling_var

HEADER_TEXT = (
    "# GENERATED by bay compile. sha256:{digest}. Do not edit; edit bay.toml or bay.fleet.toml."
)
HEADER_RE = re.compile(
    r"^# GENERATED by bay compile\. sha256:([0-9a-f]{64})\. "
    r"Do not edit; edit bay\.toml or bay\.fleet\.toml\.$"
)

#: Keys a [deploy.<env>] table may override with a plain replace.
_RUNTIME_KEYS = (
    "image", "port", "command", "release", "health", "replicas", "memory", "update",
    "zero_downtime", "logs", "secrets", "log_rotation",
)
#: bay.toml update -> services.yml update. None means: leave the key out (monitor).
_UPDATE = {"notify": None, "auto": "auto", "off": False}
#: Variables env.j2 writes for a `database:` binding.
_DB_VARS = ("DATABASE_URL", "DB_HOST", "DB_PORT", "DB_NAME", "DB_USER", "DB_PASSWORD")
_PG_PORT = 5432
_REDIS_PORT = 6379
#: Names the deploy code derives from a container name: routers and the canary.
_DERIVED_SUFFIXES = ("-vpn", "-public", "-health", "-new")
#: services.schema.json: what a route may contain.
_ROUTE_RE = re.compile(r"^/[A-Za-z0-9._~%+/*-]*$")


class CompileError(Exception):
    """The inputs cannot be compiled. ``lines`` holds one message each."""

    def __init__(self, lines: list[str]) -> None:
        super().__init__("\n".join(lines))
        self.lines = lines


@dataclass(frozen=True, order=True)
class Unsupported:
    """A bay.toml feature the deploy code cannot express yet."""

    project: str
    path: str
    feature: str

    def __str__(self) -> str:
        return f"# TODO(role) {self.project}: {self.path}: {self.feature}"


@dataclass
class CompileResult:
    services: dict[str, dict[str, Any]]
    accessories: dict[str, dict[str, Any]]
    webhook: dict[str, str] | None
    unsupported: list[Unsupported] = field(default_factory=list)
    #: Lines for the reader (a mounted file found in its old place). Never in the file.
    notes: list[str] = field(default_factory=list)
    #: ``[tailnet.routes]`` as the map the traefik and headscale templates read.
    tailnet_proxies: dict[str, dict[str, Any]] = field(default_factory=dict)

    def data(self) -> dict[str, Any]:
        out: dict[str, Any] = {"accessories": self.accessories, "services": self.services}
        if self.webhook is not None:
            out["webhook"] = self.webhook
        if self.tailnet_proxies:
            # Only when routes exist, so a fleet without them compiles to the same bytes.
            out["tailnet_proxies"] = self.tailnet_proxies
        return out

    def body(self) -> str:
        """The file without its header line. Deterministic."""
        import yaml

        data = self.data()
        proxies = data.pop("tailnet_proxies", None)
        dumped: str = yaml.safe_dump(
            data,
            sort_keys=True,
            default_flow_style=False,
            allow_unicode=True,
            width=4096,
            explicit_start=True,
        )
        if proxies:
            # Routes keep the order of bay.fleet.toml: the traefik and headscale
            # templates render them in that order, so an imported fleet renders
            # the same bytes as its old tailnet_proxies.yml did.
            dumped += yaml.safe_dump(
                {"tailnet_proxies": proxies},
                sort_keys=False,
                default_flow_style=False,
                allow_unicode=True,
                width=4096,
            )
        if not self.unsupported:
            return dumped
        head, rest = dumped.split("\n", 1)
        todo = "".join(f"{u}\n" for u in self.unsupported)
        return f"{head}\n{todo}{rest}"

    def text(self) -> str:
        body = self.body()
        return header_for(body) + "\n" + body


def header_for(body: str) -> str:
    return HEADER_TEXT.format(digest=hashlib.sha256(body.encode("utf-8")).hexdigest())


def split_header(text: str) -> tuple[str | None, str]:
    """Return (recorded digest or None, body) for a file on disk."""
    first, sep, rest = text.partition("\n")
    match = HEADER_RE.match(first)
    if not match:
        return None, text
    return match.group(1), rest if sep else ""


def body_digest(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


